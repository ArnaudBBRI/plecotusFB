const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'assets/species/photos.json'), 'utf8'));
const photos = manifest.filter(item => !/sketch|drawing|illustration|map|skull|skeleton|specimen/i.test(item.fileTitle)
  && !/illustrat(?:ion|ed)|drawing|sketch|lithograph|engraving|aquarelle|watercolou?r|painting|Schreber/i.test(item.description)).map(item => ({
  code: item.code, scientificName: item.scientificName, src: 'assets/species/' + item.fileName,
  author: item.author, license: item.license, licenseUrl: item.licenseUrl,
  sourceUrl: item.sourceUrl, alt: 'Photographie de ' + item.scientificName
}));
const source = `(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory(require('./species.js'));
  else root.PlecotusSpeciesPhotos = factory(root.BatSpeciesNames);
})(typeof globalThis !== 'undefined' ? globalThis : this, function (Names) {
  'use strict';
  // Generated by tools/build-species-photos.cjs from the attributed photo catalog.
  const catalog = Object.freeze(${JSON.stringify(photos, null, 2)}.map(Object.freeze));
  const byCode = new Map(catalog.map(photo => [photo.code, photo]));
  function resolve(label) {
    const species = Names.resolve(label);
    return species.known && species.isSpecies ? byCode.get(species.code) || null : null;
  }
  return Object.freeze({ catalog, resolve });
});
`;
fs.writeFileSync(path.join(root, 'species-photos.js'), source);
const credits = ['# Photographies des espèces', '',
  'Photographies de Wikimedia Commons et iNaturalist, téléchargées le 8 novembre 2026.',
  'Les miniatures sont redimensionnées et affichées dans un cadre recadré. Elles sont intégrées à Plecotus pour un affichage hors ligne. Les liens de crédit restent accessibles dans les infobulles.',
  'Dans la version autonome, les images sont encodées dans Plecotus.html. Les chemins ci-dessous désignent les fichiers du code source.', ''];
for(const photo of photos) credits.push('## ' + photo.scientificName + ' (' + photo.code + ')', '',
  'Titre source : ' + manifest.find(item => item.code === photo.code).fileTitle.replace(/^File:/, ''), '',
  'Auteur : ' + photo.author, '', 'Licence : [' + photo.license + '](' + photo.licenseUrl + ')', '',
  '[Fichier source et conditions de réutilisation](' + photo.sourceUrl + ')', '', 'Fichier local : ' + photo.src, '');
fs.writeFileSync(path.join(root, 'assets/species/ATTRIBUTIONS.md'), credits.join('\n'));
console.log('Built species photo catalog: ' + photos.length + ' photographs.');
