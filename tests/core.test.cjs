const test = require('node:test');
const assert = require('node:assert/strict');
const Core = require('../core.js');

const headers = ['IN FILE', 'FOLDER', 'DATE', 'DATE-12', 'AUTO ID', 'PULSES', 'MATCHING', 'MATCH RATIO', 'MARGIN', 'OFFSET', 'CHANNEL', 'MANUAL ID'];
function contact(file, autoId, pulses, matching, ratio, margin, overrides = {}) {
  const values = { 'IN FILE': file, FOLDER: 'Forest', DATE: '2026-09-02', 'DATE-12': '2026-09-01', 'AUTO ID': autoId, PULSES: String(pulses), MATCHING: String(matching), 'MATCH RATIO': String(ratio), MARGIN: String(margin), OFFSET: '0', CHANNEL: '1', 'MANUAL ID': '', ...overrides };
  return headers.map(header => values[header]);
}

test('detects semicolon CSV with BOM, preamble, decimal commas, quoted and multiline cells', () => {
  const source = '\uFEFF# Kaleidoscope export\r\nGenerated by Kaleidoscope\r\n\r\nIN FILE;AUTO-ID;PULSES;MATCHING;MATCH RATIO;MARGIN;MANUAL ID\r\n"call;one.wav";Pipistrellus pipistrellus;12;9;0,75;0,22;"checked ""by""\r\nAda"\r\n';
  const parsed = Core.parseCSV(source);
  assert.equal(parsed.delimiter, ';');
  assert.deepEqual(parsed.headers, ['IN FILE', 'AUTO-ID', 'PULSES', 'MATCHING', 'MATCH RATIO', 'MARGIN', 'MANUAL ID']);
  assert.equal(parsed.records.length, 1);
  assert.equal(parsed.records[0][0], 'call;one.wav');
  assert.equal(parsed.records[0][6], 'checked "by"\r\nAda');
  assert.match(parsed.warnings[0], /préambule/);
  const analysis = Core.analyze(parsed.headers, parsed.records);
  assert.equal(analysis.rows[0].ratio, 0.75);
  assert.equal(analysis.rows[0].margin, 0.22);
  assert.equal(analysis.rows[0].manualId, 'checked "by"\r\nAda');
});

test('detects comma and tab imports and accepts a final record without newline', () => {
  for (const delimiter of [',', '\t']) {
    const parsed = Core.parseCSV(['IN FILE', 'Species Auto-ID', 'PULSES'].join(delimiter) + '\n' + ['test.wav', 'Noise', '3'].join(delimiter));
    assert.equal(parsed.delimiter, delimiter);
    assert.deepEqual(parsed.records, [['test.wav', 'Noise', '3']]);
    assert.equal(Core.analyze(parsed.headers, parsed.records).rows[0].kind, 'noise');
  }
});

test('preserves original names, field values and row order through CSV round trip', () => {
  const originalHeaders = ['IN FILE', ' AUTO_ID ', 'unknown data', 'MANUAL ID', 'MATCH RATIO'];
  const originalRecords = [
    ['line, "one".wav', '  Pipistrellus pipistrellus ', '=unchanged', '', '0.80'],
    ['two\nlines.wav', 'No ID', ' leading and trailing ', 'Myotis sp.', '75%'],
    ['\tthird.wav', 'Noise', 'c:\\folder\\recording', 'line\r\nend', '']
  ];
  for (const delimiter of [',', ';', '\t']) {
    const parsed = Core.parseCSV(Core.stringifyCSV(originalHeaders, originalRecords, delimiter));
    assert.deepEqual(parsed.headers, originalHeaders);
    assert.deepEqual(parsed.records, originalRecords);
    const analysis = Core.analyze(parsed.headers, parsed.records);
    assert.deepEqual(analysis.rows.map(row => row.raw), originalRecords);
    assert.deepEqual(analysis.rows.map(row => row.index), [0, 1, 2]);
    assert.equal(analysis.rows[0].importedAutoId, originalRecords[0][1]);
  }
});

test('rejects blank, duplicate and ambiguous canonical headers', () => {
  assert.throws(() => Core.parseCSV('IN FILE,AUTO ID,\na.wav,Noise,x'), /vide/);
  assert.throws(() => Core.parseCSV('IN FILE,AUTO ID,AUTO ID\na.wav,Noise,Noise'), /double/);
  assert.throws(() => Core.parseCSV('IN FILE,AUTO ID,AUTO_ID\na.wav,Noise,Noise'), /sans ambiguïté/);
});

test('rejects malformed rows and quotes while pads missing trailing values transparently', () => {
  assert.throws(() => Core.parseCSV('IN FILE,AUTO ID\na.wav,Noise,extra'), /contient 3 valeurs/);
  assert.throws(() => Core.parseCSV('IN FILE,AUTO ID\n"a.wav,Noise', ','), /non refermés/);
  assert.throws(() => Core.parseCSV('IN FILE,AUTO ID\n"a.wav"oops,Noise', ','), /inattendu/);
  assert.throws(() => Core.parseCSV('IN FILE,AUTO ID\n"a.wav,Noise'), /non refermés/);
  assert.throws(() => Core.parseCSV('IN FILE;AUTO ID\n"a.wav"oops;Noise'), /inattendu/);
  const parsed = Core.parseCSV('IN FILE,AUTO ID,MANUAL ID\na.wav,Noise');
  assert.deepEqual(parsed.records[0], ['a.wav', 'Noise', '']);
  assert.match(parsed.warnings[0], /cellules finales manquantes/);
});

test('ranks lexicographically within species and recording night, retaining source order', () => {
  const input = [
    contact('low.wav', 'Pipistrellus pipistrellus', 10, 6, 0.6, 0.9),
    contact('margin-low.wav', 'Pipistrellus pipistrellus', 10, 8, 0.8, 0.1),
    contact('margin-high.wav', 'Pipistrellus pipistrellus', 10, 8, 0.8, 0.5),
    contact('ratio-high.wav', 'Pipistrellus pipistrellus', 10, 8, 0.9, 0.01),
    contact('different.wav', 'Myotis daubentonii', 10, 3, 0.3, 0.2),
    contact('other-night.wav', 'Pipistrellus pipistrellus', 10, 1, 0.1, 0.1, { 'DATE-12': '2026-09-02' }),
    contact('tied.wav', 'Pipistrellus pipistrellus', 10, 8, 0.9, 0.01)
  ];
  const result = Core.analyze(headers, input);
  assert.deepEqual(result.rows.map(row => row.file), input.map(row => row[0]));
  assert.deepEqual(result.rows.map(row => row.rank), [5, 4, 3, 1, 1, 1, 2]);
  assert.deepEqual(result.groups[0].rows.map(row => row.file), ['ratio-high.wav', 'tied.wav', 'margin-high.wav', 'margin-low.wav', 'low.wav']);
  assert.equal(result.groups.length, 3);
  assert.equal(result.rows[3].isAnchor, true);
  assert.equal(result.rows[6].isAnchor, false);
  assert.equal(result.rows[4].isAnchor, true);
  assert.equal(result.groups[0].anchorId, result.rows[3].id);
});

test('missing values rank last and are never silently treated as zero', () => {
  const input = [
    contact('missing.wav', 'Pipistrellus pipistrellus', '', '', '', ''),
    contact('zero.wav', 'Pipistrellus pipistrellus', 0, 0, 0, 0),
    contact('some.wav', 'Pipistrellus pipistrellus', 10, 2, 0.2, 0.1)
  ];
  const result = Core.analyze(headers, input);
  assert.equal(result.rows[0].pulses, null);
  assert.equal(result.rows[0].matching, null);
  assert.equal(result.rows[0].ratio, null);
  assert.equal(result.rows[0].margin, null);
  assert.deepEqual(result.groups[0].rows.map(row => row.file), ['some.wav', 'zero.wav', 'missing.wav']);
  assert.match(result.rows[0].issues.join(' '), /MATCHING manquant/);
});

test('derives only missing ratios from valid matching/pulse counts and flags invalid fields', () => {
  const result = Core.analyze(headers, [
    contact('derived.wav', 'Pipistrellus pipistrellus', 10, 8, '', 0.2),
    contact('invalid-ratio.wav', 'Pipistrellus pipistrellus', 10, 8, '80', 0.2),
    contact('inconsistent.wav', 'Pipistrellus pipistrellus', 3, 8, '', 0.2),
    contact('invalid-counts.wav', 'Pipistrellus pipistrellus', '-2', '1.5', '101%', '-1'),
    contact('percent.wav', 'Pipistrellus pipistrellus', 10, 8, '80%', 0.2)
  ]);
  assert.equal(result.rows[0].ratio, 0.8);
  assert.equal(result.rows[0].ratioSource, 'derived');
  assert.equal(result.rows[1].ratio, null);
  assert.match(result.rows[1].issues.join(' '), /MATCH RATIO invalide/);
  assert.equal(result.rows[2].ratio, null);
  assert.match(result.rows[2].issues.join(' '), /MATCHING dépasse PULSES/);
  assert.equal(result.rows[3].pulses, null);
  assert.equal(result.rows[3].matching, null);
  assert.equal(result.rows[3].ratio, null);
  assert.equal(result.rows[3].margin, null);
  assert.equal(result.rows[4].ratio, 0.8);
});

test('recording segments have independent row identities; repeated locators are flagged', () => {
  const input = [
    contact('same.wav', 'Noise', 3, 0, 0, 0, { OFFSET: '0' }),
    contact('same.wav', 'Noise', 3, 0, 0, 0, { OFFSET: '5' }),
    contact('same.wav', 'Noise', 3, 0, 0, 0, { OFFSET: '0' })
  ];
  const result = Core.analyze(headers, input);
  assert.equal(new Set(result.rows.map(row => row.id)).size, 3);
  assert.match(result.rows[0].issues.join(' '), /repère d’enregistrement est répété/);
  assert.doesNotMatch(result.rows[1].issues.join(' '), /repère d’enregistrement est répété/);
  assert.equal(result.rows[0].isAnchor, false);
});

test('data issue summary excludes Noise from both counts and counts affected contacts once', () => {
  const input = [
    contact('noise-a.wav', 'Noise', '', '', '', ''),
    contact('noise-b.wav', '  noise  ', '', '', '', ''),
    contact('valid.wav', 'PIPPIP', 10, 8, 0.8, 0.2),
    contact('missing.wav', 'PIPNAT', '', '', '', ''),
    contact('noid.wav', 'No ID', 10, 8, 0.95, 0.2)
  ];
  const result = Core.analyze(headers, input);
  assert.ok(result.rows[3].issues.length > 1);
  assert.deepEqual(result.warnings.filter(warning => warning.includes('anomalies de données')), [
    '2 contact(s) sur 3 présentent des anomalies de données (hors Noise).'
  ]);
  assert.equal(result.rows.length, 5);
  assert.ok(result.rows[0].issues.length > 0);
  assert.deepEqual(result.rows.map(row => row.raw), input);
});

test('Noise-only issues and duplicate locators do not trigger data quality summary warnings', () => {
  const result = Core.analyze(headers, [
    contact('noise.wav', 'Noise', '', '', '', ''),
    contact('noise.wav', 'NOISE', '', '', '', '')
  ]);
  assert.deepEqual(result.warnings, []);
  assert.equal(result.rows.length, 2);
  for (const row of result.rows) assert.match(row.issues.join(' '), /repère d’enregistrement est répété/);
});

test('duplicate locator summary counts only non-Noise contacts', () => {
  const result = Core.analyze(headers, [
    contact('noise.wav', 'Noise', 0, 0, 0, 0),
    contact('noise.wav', 'Noise', 0, 0, 0, 0),
    contact('bat.wav', 'PIPPIP', 10, 8, 0.8, 0.2),
    contact('bat.wav', 'PIPPIP', 10, 8, 0.8, 0.2)
  ]);
  assert.match(result.warnings.find(warning => warning.includes('repères')), /^2 contacts hors Noise/);
  assert.match(result.warnings.find(warning => warning.includes('anomalies de données')), /^2 contact\(s\) sur 2 /);
});

test('an impossible inflated MATCHING count cannot become the reference pick', () => {
  const result = Core.analyze(headers, [
    contact('invalid-inflated.wav', 'Pipistrellus pipistrellus', 5, 99, 1, 9),
    contact('valid.wav', 'Pipistrellus pipistrellus', 10, 6, 0.6, 0.1)
  ]);
  assert.equal(result.rows[0].matching, null);
  assert.equal(result.rows[0].raw[6], '99');
  assert.equal(result.rows[0].pulses, 5);
  assert.equal(result.rows[0].isAnchor, false);
  assert.equal(result.rows[1].isAnchor, true);
  assert.equal(result.groups[0].rows[0].file, 'valid.wav');
});

test('flags contradictory imported ratios without replacing them, allowing recorded rounding', () => {
  const result = Core.analyze(headers, [
    contact('rounded.wav', 'Pipistrellus pipistrellus', 22, 18, '0.818', 0.1),
    contact('contradictory.wav', 'Pipistrellus pipistrellus', 10, 8, '0.95', 0.1),
    contact('rounded-percent.wav', 'Pipistrellus pipistrellus', 22, 18, '82%', 0.1),
    contact('contradictory-endpoint.wav', 'Pipistrellus pipistrellus', 10, 8, '1', 0.1)
  ]);
  assert.doesNotMatch(result.rows[0].issues.join(' '), /MATCH RATIO differs/);
  assert.match(result.rows[1].issues.join(' '), /MATCH RATIO diffère/);
  assert.equal(result.rows[1].ratio, 0.95);
  assert.equal(result.rows[1].ratioSource, 'imported');
  assert.doesNotMatch(result.rows[2].issues.join(' '), /MATCH RATIO differs/);
  assert.match(result.rows[3].issues.join(' '), /MATCH RATIO diffère/);
});

